-- CDBALP.pf (Card Balance Physical File)
CREATE TABLE CDBALP_CDBALP(
--- TECHNICAL IDENTIFIER (USED FOR FIFO/LIFO)
    IDENTIFIER BIGSERIAL PRIMARY KEY,
    CARDNUM DECIMAL(16,0) NOT NULL DEFAULT 0,
    CUSTID DECIMAL(9,0) NOT NULL DEFAULT 0,
    ACCTNUM DECIMAL(12,0) NOT NULL DEFAULT 0,
    OUTSTANDBAL NUMERIC(11,2) NOT NULL DEFAULT 0,
    TOTPURCHASE NUMERIC(11,2) NOT NULL DEFAULT 0,
    TOTPAYMENT NUMERIC(11,2) NOT NULL DEFAULT 0,
    TOTCASHADVANCE NUMERIC(11,2) NOT NULL DEFAULT 0,
    TOTREFUND NUMERIC(11,2) NOT NULL DEFAULT 0,
    DUEDATE DATE NOT NULL DEFAULT CURRENT_DATE,
    PAYMENTSTATUS CHAR(1) NOT NULL DEFAULT 'U',
    LASTUPDDATE DATE NOT NULL DEFAULT CURRENT_DATE,
    LASTUPDTIME TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    BALCRTDT DECIMAL(7,0) NOT NULL DEFAULT 0,
    BALCRTTM DECIMAL(6,0) NOT NULL DEFAULT 0,
    BALCHGDT DECIMAL(7,0) NOT NULL DEFAULT 0,
    BALCHGTM DECIMAL(6,0) NOT NULL DEFAULT 0,
-- EXTRA COLUMNS
    _LASTUPDATE_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    _CREATION_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    SRCFILE CHARACTER(10) DEFAULT 'CDBALP',
    MEMBER CHARACTER(10) DEFAULT 'CDBALP',
-- UNIQUE CONSTRAINT
    CONSTRAINT CDBALP_UNIQUE_CARD UNIQUE (CARDNUM)
);

-- COMMENTS
COMMENT ON COLUMN CDBALP_CDBALP.CARDNUM IS 'CREDIT CARD NUMBER';
COMMENT ON COLUMN CDBALP_CDBALP.CUSTID IS 'CUSTOMER ID';
COMMENT ON COLUMN CDBALP_CDBALP.ACCTNUM IS 'ACCOUNT NUMBER';
COMMENT ON COLUMN CDBALP_CDBALP.OUTSTANDBAL IS 'OUTSTANDING BALANCE';
COMMENT ON COLUMN CDBALP_CDBALP.TOTPURCHASE IS 'TOTAL PURCHASES';
COMMENT ON COLUMN CDBALP_CDBALP.TOTPAYMENT IS 'TOTAL PAYMENTS';
COMMENT ON COLUMN CDBALP_CDBALP.TOTCASHADVANCE IS 'TOTAL CASH ADVANCES';
COMMENT ON COLUMN CDBALP_CDBALP.TOTREFUND IS 'TOTAL REFUNDS';
COMMENT ON COLUMN CDBALP_CDBALP.DUEDATE IS 'PAYMENT DUE DATE';
COMMENT ON COLUMN CDBALP_CDBALP.PAYMENTSTATUS IS 'PAYMENT STATUS (P=Paid, U=Unpaid, O=Overdue)';
COMMENT ON COLUMN CDBALP_CDBALP.LASTUPDDATE IS 'LAST UPDATE DATE';
COMMENT ON COLUMN CDBALP_CDBALP.LASTUPDTIME IS 'LAST UPDATE TIMESTAMP';
COMMENT ON COLUMN CDBALP_CDBALP.BALCRTDT IS 'BAL CREATE DATE';
COMMENT ON COLUMN CDBALP_CDBALP.BALCRTTM IS 'BAL CREATE TIME';
COMMENT ON COLUMN CDBALP_CDBALP.BALCHGDT IS 'BAL CHANGE DATE';
COMMENT ON COLUMN CDBALP_CDBALP.BALCHGTM IS 'BAL CHANGE TIME';

-- PARTITION TABLE
CREATE TABLE CDBALP (LIKE CDBALP_CDBALP INCLUDING COMMENTS INCLUDING CONSTRAINTS INCLUDING DEFAULTS INCLUDING IDENTITY) PARTITION BY RANGE (SRCFILE, MEMBER);

-- ATTACH DEFAULT MEMBER TABLE TO PARTITION TABLE
ALTER TABLE CDBALP ATTACH PARTITION CDBALP_CDBALP FOR VALUES FROM ('CDBALP', 'CDBALP') TO ('CDBALP', 'CDBAPz');

-- INDEXES
CREATE INDEX CDBALP_CARDNUM_IDX ON CDBALP_CDBALP(CARDNUM);
CREATE INDEX CDBALP_CUSTID_IDX ON CDBALP_CDBALP(CUSTID);
CREATE INDEX CDBALP_ACCTNUM_IDX ON CDBALP_CDBALP(ACCTNUM);
CREATE INDEX CDBALP_DUEDATE_IDX ON CDBALP_CDBALP(DUEDATE);
CREATE INDEX CDBALP_PAYMENTSTATUS_IDX ON CDBALP_CDBALP(PAYMENTSTATUS);

COMMIT;